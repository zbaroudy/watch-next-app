"""
Trakt list data access.

Reads the already-resolved Trakt -> TMDB JSON generated by the
Trakt POC and exposes a simple interface for the FastAPI application.

This module does NOT scrape Trakt and does NOT call TMDB.

The scraper/resolver remain separate processes for now.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


# --------------------------------------------------
# Paths
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent.parent

TRAKT_DATA_DIR = BASE_DIR / "data" / "trakt"

ALL_LISTS_FILE = TRAKT_DATA_DIR / "tmdb_all_lists.json"
FAILED_FILE = TRAKT_DATA_DIR / "tmdb_all_lists_failed.json"
PER_LIST_DIR = TRAKT_DATA_DIR / "tmdb_lists"


# --------------------------------------------------
# Internal helpers
# --------------------------------------------------

def _load_json(path: Path, default: Any) -> Any:
    """
    Load JSON safely.

    Returns the supplied default if the file does not exist
    or contains invalid JSON.
    """

    if not path.exists():
        return default

    try:
        with path.open("r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return default


def _normalize_item(item: dict) -> dict:
    """
    Convert a raw resolver item into the application's
    normalized Trakt/TMDB representation.

    The original Trakt fields are retained so we don't lose
    information from the POC.
    """

    tmdb = item.get("tmdb") or {}

    media_type = item.get("type")

    if media_type not in ("movie", "show"):
        media_type = tmdb.get("tmdb_type")

    return {
        # Trakt information
        "title": item.get("title"),
        "subtitle": item.get("subtitle"),
        "year": item.get("year"),
        "type": media_type,
        "trakt_id": item.get("trakt_id"),
        "tags": item.get("tags") or [],
        "trakt_image_url": item.get("image_url"),

        # List information
        "list_name": item.get("list_name"),
        "list_slug": item.get("list_slug"),

        # TMDB information
        "tmdb_id": tmdb.get("tmdb_id"),
        "tmdb_title": tmdb.get("tmdb_title"),
        "tmdb_original_title": tmdb.get(
            "tmdb_original_title"
        ),
        "tmdb_date": tmdb.get("tmdb_date"),
        "tmdb_type": tmdb.get("tmdb_type"),
        "tmdb_overview": tmdb.get("tmdb_overview"),
        "tmdb_poster_path": tmdb.get(
            "tmdb_poster_path"
        ),
        "tmdb_backdrop_path": tmdb.get(
            "tmdb_backdrop_path"
        ),
        "tmdb_vote_average": tmdb.get(
            "tmdb_vote_average"
        ),
        "tmdb_vote_count": tmdb.get(
            "tmdb_vote_count"
        ),

        # Match diagnostics
        "match_method": tmdb.get(
            "match_method"
        ),
        "match_score": tmdb.get(
            "match_score"
        ),
        "match_confidence": tmdb.get(
            "match_confidence"
        ),
    }


# --------------------------------------------------
# Public API
# --------------------------------------------------

def is_available() -> bool:
    """
    Return True when resolved Trakt/TMDB data exists.
    """

    return ALL_LISTS_FILE.exists()


def get_all_items() -> list[dict]:
    """
    Return every successfully resolved Trakt item.
    """

    data = _load_json(
        ALL_LISTS_FILE,
        []
    )

    if not isinstance(data, list):
        return []

    return [
        _normalize_item(item)
        for item in data
        if isinstance(item, dict)
    ]


def get_failed_items() -> list[dict]:
    """
    Return items that failed TMDB resolution.
    """

    data = _load_json(
        FAILED_FILE,
        []
    )

    if not isinstance(data, list):
        return []

    return data


def get_lists() -> list[dict]:
    """
    Return a summary of all available Trakt lists.

    Lists are derived from the resolved data rather than from
    a separate configuration file. This means the API always
    reflects the data that was actually generated.
    """

    items = get_all_items()

    lists: dict[str, dict] = {}

    for item in items:
        slug = item.get("list_slug")
        name = item.get("list_name")

        if not slug:
            continue

        if slug not in lists:
            lists[slug] = {
                "slug": slug,
                "name": name or slug,
                "count": 0,
                "movies": 0,
                "shows": 0,
            }

        lists[slug]["count"] += 1

        if item.get("type") == "movie":
            lists[slug]["movies"] += 1

        elif item.get("type") == "show":
            lists[slug]["shows"] += 1

    return sorted(
        lists.values(),
        key=lambda x: x["name"].lower()
    )


def get_list(
    slug: str,
) -> list[dict]:
    """
    Return all resolved items belonging to one Trakt list.
    """

    items = get_all_items()

    return [
        item
        for item in items
        if item.get("list_slug") == slug
    ]


def get_list_info(
    slug: str,
) -> dict | None:
    """
    Return metadata and counts for a specific list.
    """

    items = get_list(slug)

    if not items:
        return None

    first = items[0]

    movies = sum(
        1
        for item in items
        if item.get("type") == "movie"
    )

    shows = sum(
        1
        for item in items
        if item.get("type") == "show"
    )

    return {
        "slug": slug,
        "name": first.get("list_name") or slug,
        "count": len(items),
        "movies": movies,
        "shows": shows,
    }


def get_item(
    tmdb_id: int | str,
) -> dict | None:
    """
    Find a Trakt-list item by TMDB ID.

    Useful later when connecting Trakt-list titles to the
    application's existing title detail pages.
    """

    try:
        tmdb_id = int(tmdb_id)
    except (TypeError, ValueError):
        return None

    for item in get_all_items():
        if item.get("tmdb_id") == tmdb_id:
            return item

    return None


def get_stats() -> dict:
    """
    Return overall Trakt/TMDB statistics.
    """

    items = get_all_items()
    failed = get_failed_items()

    # Build the list count from the already-loaded items instead of
    # calling get_lists(), which would read the same JSON file again.
    list_slugs = {
        item.get("list_slug")
        for item in items
        if item.get("list_slug")
    }

    movies = sum(
        1
        for item in items
        if item.get("type") == "movie"
    )

    shows = sum(
        1
        for item in items
        if item.get("type") == "show"
    )

    return {
        "available": is_available(),
        "total": len(items),
        "movies": movies,
        "shows": shows,
        "failed": len(failed),
        "lists": len(list_slugs),
    }
